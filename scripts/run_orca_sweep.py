"""
run_orca_sweep.py
-----------------
B1: tune ORCA on VALIDATION seeds only (see the Stage-2 test plan, "ORCA tuning").

Grid, fixed before tuning, after a first look at the defaults on 6 validation tests
(everything else stays at baselines/orca.py's defaults):
    time_horizon       2, 4 s            look-ahead for other drones
    time_horizon_obst  1, 2 s            look-ahead for obstacles
    radius             0.25, 0.35, 0.5 m per drone (two drones keep 2 x radius apart)
    obstacle_radius    0.3, 0.45 m       drone centre to an obstacle point
= 24 settings per ORCA variant (orca = LiDAR ring, orca_map = true shapes).

All runs use goal-hold and the per-episode noise seed
(configs/config_stage2_round7_eval_goalhold.yaml + an orca: block per setting).

Stages:
    screen   all 24 settings, the 13 selection tests (standard 9 + crowd 4),
             validation seeds 20-24, 10 episodes per seed (50 flights per test)
    rank     prints the ranking of a stage
    confirm  the top N of the screen, all 17 tests, 20 episodes per seed (100 per test)
Selection (screen and confirm): highest strict success over standard 9 + crowd 4,
ties broken by fewer crashes. Held-out is never used.

Each setting's config is written next to its results
(eval_results/b1_orca_sweep/configs/), so every run records exactly what it used.
Stopped runs resume: run_suite skips tests that already have a summary.json.

Examples (repo root; two terminals share the work with --shard):
    python scripts/run_orca_sweep.py --variant orca --stage screen --shard 0 --shards 2
    python scripts/run_orca_sweep.py --variant orca --stage screen --shard 1 --shards 2
    python scripts/run_orca_sweep.py --variant orca --stage rank
    python scripts/run_orca_sweep.py --variant orca --stage confirm --top 3 --shard 0 --shards 2
    python scripts/run_orca_sweep.py --variant orca --stage rank --of confirm
"""

import argparse
import glob
import itertools
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE_CONFIG = os.path.join('configs', 'config_stage2_round7_eval_goalhold.yaml')
OUT_ROOT = os.path.join('eval_results', 'b1_orca_sweep')
VAL_SEEDS = ['20', '21', '22', '23', '24']

GRID = {
    'time_horizon': [2.0, 4.0],
    'time_horizon_obst': [1.0, 2.0],
    'radius': [0.25, 0.35, 0.5],
    'obstacle_radius': [0.3, 0.45],
}


def settings():
    """Every grid point as (tag, {key: value}), in a fixed order."""
    keys = list(GRID)
    out = []
    for values in itertools.product(*(GRID[k] for k in keys)):
        s = dict(zip(keys, values))
        tag = (f"th{s['time_horizon']:g}_tho{s['time_horizon_obst']:g}"
               f"_r{s['radius']:g}_or{s['obstacle_radius']:g}")
        out.append((tag, s))
    return out


def write_config(variant, tag, s):
    """The goal-hold eval config + this setting's orca: block (text kept, comments too)."""
    os.makedirs(os.path.join(OUT_ROOT, 'configs'), exist_ok=True)
    path = os.path.join(OUT_ROOT, 'configs', f'{variant}_{tag}.yaml')
    with open(BASE_CONFIG, encoding='utf-8') as f:
        text = f.read().rstrip('\n')
    block = ("\n\norca:                          # B1 sweep setting (scripts/run_orca_sweep.py)\n"
             + "".join(f"  {k}: {v:g}\n" for k, v in s.items()))
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f"# Generated by scripts/run_orca_sweep.py: {BASE_CONFIG} + orca setting {tag}\n")
        f.write(text + block)
    return path


def run_name(variant, tag, stage):
    return f'{variant}_{tag}_{stage}'


def score(name):
    """(successes, crashes, flights) over standard 9 + crowd 4 for one run; None if incomplete."""
    succ = crash = n = 0
    files = []
    for group in ('standard', 'crowd'):
        files += glob.glob(os.path.join(OUT_ROOT, name, group, '*', 'summary.json'))
    if len(files) < 13:
        return None
    for f in files:
        s = json.load(open(f, encoding='utf-8'))
        e = s['episodes']
        succ += round(s['success_rate'] * e)
        crash += round(s.get('any_crash_rate', s.get('collision_rate', 0.0)) * e)
        n += e
    return succ, crash, n


def ranking(variant, stage):
    rows = []
    for tag, s in settings():
        r = score(run_name(variant, tag, stage))
        if r is not None:
            rows.append((tag, *r))
    rows.sort(key=lambda r: (-r[1], r[2]))        # most successes, then fewest crashes
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--variant', required=True, choices=['orca', 'orca_map'])
    ap.add_argument('--stage', required=True, choices=['screen', 'confirm', 'rank'])
    ap.add_argument('--of', default='screen', choices=['screen', 'confirm'], help="--stage rank: which stage")
    ap.add_argument('--top', type=int, default=3, help="--stage confirm: how many screened settings")
    ap.add_argument('--shard', type=int, default=0)
    ap.add_argument('--shards', type=int, default=1)
    ap.add_argument('--jobs', type=int, default=2)
    args = ap.parse_args()
    os.chdir(ROOT)

    if args.stage == 'rank':
        rows = ranking(args.variant, args.of)
        print(f"{args.variant} {args.of}: {len(rows)} of {len(settings())} settings complete "
              f"(standard 9 + crowd 4; ties -> fewer crashes; held-out not used)")
        for i, (tag, succ, crash, n) in enumerate(rows, 1):
            print(f"{i:3d}  {tag:24s} success {succ:5d}/{n} = {100 * succ / n:5.1f}%   crashes {crash}")
        return

    if args.stage == 'screen':
        todo = settings()
        groups, episodes = ['standard', 'crowd'], '10'
    else:
        top = [r[0] for r in ranking(args.variant, 'screen')[:args.top]]
        if len(top) < args.top:
            sys.exit("the screen isn't complete yet: run --stage rank to see what is missing")
        todo = [(tag, s) for tag, s in settings() if tag in top]
        groups, episodes = ['standard', 'crowd', 'heldout'], '20'

    mine = todo[args.shard::args.shards]
    print(f"{args.variant} {args.stage}: {len(mine)} of {len(todo)} settings in shard "
          f"{args.shard}/{args.shards}")
    for tag, s in mine:
        cfg = write_config(args.variant, tag, s)
        cmd = [sys.executable, os.path.join('scripts', 'run_suite.py'),
               '--name', run_name(args.variant, tag, args.stage), '--policy', args.variant,
               '--config', cfg, '--groups', *groups, '--seeds', *VAL_SEEDS,
               '--episodes', episodes, '--jobs', str(args.jobs), '--root', OUT_ROOT]
        print(' '.join(cmd), flush=True)
        subprocess.run(cmd, check=True)


if __name__ == '__main__':
    main()
